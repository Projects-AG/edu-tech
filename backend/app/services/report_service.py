def _scoped_submission_query(
    db: Session,
    institution_id: int | None,
    department_id: int | None = None,
):
    query = db.query(Submission)
    if institution_id:
        query = query.filter(Submission.institution_id == institution_id)
    if department_id:
        query = query.filter(Submission.department_id == department_id)
    return query


def _scoped_document_query(
    db: Session,
    institution_id: int | None,
    department_id: int | None = None,
):
    query = db.query(Document)
    if institution_id:
        query = query.filter(Document.institution_id == institution_id)
    if department_id:
        query = query.join(
            Submission,
            Document.submission_id == Submission.id,
        ).filter(Submission.department_id == department_id)
    return query


def _scoped_review_query(
    db: Session,
    institution_id: int | None,
    department_id: int | None = None,
):
    query = db.query(Review)
    if institution_id or department_id:
        query = query.join(
            Submission,
            Submission.id == Review.submission_id,
        )
        if institution_id:
            query = query.filter(Submission.institution_id == institution_id)
        if department_id:
            query = query.filter(Submission.department_id == department_id)
    return query


def calculate_institution_reports(
    db: Session,
    institution_id: int = None,
    department_id: int | None = None,
) -> dict:
    sub_query = _scoped_submission_query(db, institution_id, department_id)
    doc_query = _scoped_document_query(db, institution_id, department_id)
    dept_query = db.query(Department)
    if institution_id:
        dept_query = dept_query.filter(Department.institution_id == institution_id)
    if department_id:
        dept_query = dept_query.filter(Department.id == department_id)
    review_query = _scoped_review_query(db, institution_id, department_id)

    total_submissions = sub_query.count()
    draft_count = sub_query.filter(Submission.status == "Draft").count()
    submitted_count = sub_query.filter(Submission.status == "Submitted").count()
    under_review_count = sub_query.filter(Submission.status == "Under Review").count()
    resubmitted_count = sub_query.filter(Submission.status == "Resubmitted").count()
    approved_count = sub_query.filter(Submission.status == "Approved").count()
    rejected_count = sub_query.filter(Submission.status == "Rejected").count()
    changes_requested_count = sub_query.filter(
        Submission.status == "Changes Requested"
    ).count()
    final_approval_count = sub_query.filter(
        Submission.status == "Final Approval"
    ).count()
    final_submitted_count = sub_query.filter(
        Submission.status == "Final Submitted"
    ).count()

    institution_funnel = {
        "total": total_submissions,
        "draft": draft_count,
        "submitted": submitted_count,
        "under_review": under_review_count,
        "resubmitted": resubmitted_count,
        "approved": approved_count,
        "rejected": rejected_count,
        "changes_requested": changes_requested_count,
        "final_approval": final_approval_count,
        "final_submitted": final_submitted_count,
    }
    funnel = institution_funnel

    all_submissions = sub_query.all()
    documents = doc_query.order_by(Document.id.desc()).all()
    submissions_by_id = {}
    submission_ids = [
        document.submission_id
        for document in documents
        if document.submission_id
    ]
    if submission_ids:
        related = (
            db.query(Submission)
            .filter(Submission.id.in_(submission_ids))
            .all()
        )
        submissions_by_id = {item.id: item for item in related}

    evidence_approved = 0
    evidence_pending = 0
    evidence_rejected = 0
    evidence_items = []

    for document in documents:
        submission = submissions_by_id.get(document.submission_id)
        submission_status = submission.status if submission else None

        if submission_status in REJECTED_SUBMISSION_STATUSES:
            bucket = "rejected"
            evidence_rejected += 1
        elif submission_status in APPROVED_SUBMISSION_STATUSES:
            bucket = "approved"
            evidence_approved += 1
        else:
            bucket = "pending"
            evidence_pending += 1

        evidence_items.append({
            "document_id": document.id,
            "title": document.title,
            "document_status": document.status,
            "submission_id": document.submission_id,
            "submission_status": submission_status,
            "classification": bucket,
        })

    progress = build_progress(
        db,
        institution_id,
        department_id,
    )
    criterion_metrics = progress["criteria"]
    cycle_progress = progress["cycle_progress"]
    overall_completion = cycle_progress["completion_percentage"]
    approval_rate = (
        round((approved_count / total_submissions * 100), 1)
        if total_submissions > 0
        else 0.0
    )

    department_metrics = []
    for department in dept_query.order_by(Department.id).all():
        dept_submissions = [
            item for item in all_submissions
            if item.department_id == department.id
        ]
        d_subs = len(dept_submissions)
        d_app = len([
            item for item in dept_submissions
            if item.status in APPROVED_SUBMISSION_STATUSES
        ])
        cycle_id = cycle_progress.get("cycle_id")
        cycle_dept_subs = [
            item for item in dept_submissions
            if cycle_id and item.cycle_id == cycle_id
        ]
        department_metrics.append({
            "id": department.id,
            "name": department.name,
            "code": department.code,
            "total_submissions": d_subs,
            "cycle_submissions": len(cycle_dept_subs),
            "approved_submissions": d_app,
            "completion_percentage": (
                round((d_app / d_subs * 100), 1) if d_subs > 0 else 0.0
            ),
        })

    review_approved = review_query.filter(Review.status == "Approved").count()
    review_rejected = review_query.filter(Review.status == "Rejected").count()
    review_changes = review_query.filter(Review.status == "Changes Requested").count()

    cycle_id = cycle_progress.get("cycle_id")
    cycle_submissions = [
        item for item in all_submissions
        if cycle_id and item.cycle_id == cycle_id
    ]
    cycle_funnel = _funnel_from_submissions(cycle_submissions)

    return {
        "overall_completion_percentage": overall_completion,
        "approval_rate_percentage": approval_rate,
        "submission_funnel": funnel,
        "institution_funnel": institution_funnel,
        "cycle_funnel": cycle_funnel,
        "evidence": {
            "total_documents": len(documents),
            "approved": evidence_approved,
            "pending": evidence_pending,
            "rejected": evidence_rejected,
            "pending_evidence": evidence_pending,
            "items": evidence_items,
        },
        "criterion_report": criterion_metrics,
        "criterion_performance": criterion_metrics,
        "progress_report": {
            "submission_funnel": funnel,
            "review_activity": {
                "total": review_approved + review_rejected + review_changes,
                "approved": review_approved,
                "rejected": review_rejected,
                "changes_requested": review_changes,
            },
            "criterion_progress": criterion_metrics,
        },
        "department_performance": department_metrics,
        "cycle_progress": cycle_progress,
    }


STATUS_PRIORITY = (
    "Final Submitted",
    "Final Approval",
    "Approved",
    "Under Review",
    "Changes Requested",
    "Resubmitted",
    "Submitted",
    "Draft",
    "Rejected",
)


def _legacy_eligibility_reason(
    eligible: bool,
    final_submitted_count: int,
    final_approval_count: int,
    total_submissions: int,
) -> str:
    if eligible:
        return (
            "At least one submission has completed final submission. "
            "The institution final report can be downloaded."
        )
    if final_approval_count > 0:
        return (
            "Principal / Director has granted final approval, "
            "but final submission is not complete."
        )
    if total_submissions == 0:
        return "No submissions exist yet for this scope."
    return (
        "The final report is not eligible until Principal / Director "
        "completes final approval and final submission."
    )


def _current_submission_status(submissions: list[Submission]) -> str | None:
    if not submissions:
        return None
    statuses = {item.status for item in submissions}
    for status_name in STATUS_PRIORITY:
        if status_name in statuses:
            return status_name
    return submissions[0].status


def _metric_needs_evidence(
    metric: Metric,
    requirements: list[EvidenceRequirement],
) -> bool:
    if metric.requires_evidence:
        return True
    return any(item.required for item in requirements)


def _finalized_submissions_have_document(
    finalized_submissions: list[Submission],
    documents: list[Document],
) -> bool:
    submission_ids = {item.id for item in finalized_submissions}
    if not submission_ids:
        return False
    return any(document.submission_id in submission_ids for document in documents)


def _eligibility_metric_item(
    item: dict,
    reason: str,
    current_status: str | None,
) -> dict:
    return {
        "metric_id": item["metric_id"],
        "metric_code": item["metric_code"],
        "metric_title": item["metric_title"],
        "required": True,
        "criterion_id": item["criterion_id"],
        "criterion_number": item["criterion_number"],
        "criterion_title": item["criterion_title"],
        "current_status": current_status,
        "reason": reason,
    }


def get_final_report_eligibility(
    db: Session,
    institution_id: int | None,
) -> dict:
    if institution_id is None:
        return {
            "required_status": "Final Submitted",
            "final_submitted_count": 0,
            "final_approval_count": 0,
            "total_submissions": 0,
            "cycle_id": None,
            "cycle_name": None,
            "applicability_configured": False,
            "uses_catalog_fallback": False,
            "total_applicable_metrics": 0,
            "required_metric_count": 0,
            "optional_metric_count": 0,
            "finalized_required_count": 0,
            "pending_required_count": 0,
            "missing_required_metrics": [],
            "missing_required_evidence": [],
            "finalized_metrics": [],
            "optional_pending_metrics": [],
            "criterion_readiness": [],
            "institution_total_submissions": 0,
            "institution_final_submitted_count": 0,
            "eligible": False,
            "eligibility_status": "ADMIN_UNSCOPED",
            "naac_required_optional_verified": None,
            "reason": (
                "Final Report eligibility requires an explicit institution "
                "scope. An all-institutions Admin view does not select an "
                "arbitrary institution's active cycle."
            ),
        }

    query = _scoped_submission_query(db, institution_id)
    final_submitted_count = query.filter(
        Submission.status == "Final Submitted"
    ).count()
    final_approval_count = query.filter(
        Submission.status == "Final Approval"
    ).count()
    total_submissions = query.count()

    cycle, configured, applicable = resolve_progress_cycle(
        db,
        institution_id,
    )

    catalog_fallback = (
        cycle is not None and uses_working_catalog_fallback(db, cycle)
    )
    official_unverified = cycle_has_unverified_official_requirement_rules(
        db,
        cycle,
    )
    base = {
        "required_status": "Final Submitted",
        "final_submitted_count": final_submitted_count,
        "final_approval_count": final_approval_count,
        "total_submissions": total_submissions,
        "cycle_id": cycle.id if cycle else None,
        "cycle_name": cycle.name if cycle else None,
        "applicability_configured": configured,
        "uses_catalog_fallback": (not configured) and catalog_fallback,
        "total_applicable_metrics": 0,
        "required_metric_count": 0,
        "optional_metric_count": 0,
        "finalized_required_count": 0,
        "pending_required_count": 0,
        "missing_required_metrics": [],
        "missing_required_evidence": [],
        "finalized_metrics": [],
        "optional_pending_metrics": [],
        "criterion_readiness": [],
        "naac_required_optional_verified": (
            False if official_unverified else None
        ),
    }

    if not configured:
        if cycle and not catalog_fallback:
            official_operational_count = 0
            if getattr(cycle, "framework_id", None):
                framework = (
                    db.query(NaacFramework)
                    .filter(NaacFramework.id == cycle.framework_id)
                    .first()
                )
                if framework:
                    official_operational_count = len(
                        official_operational_metric_rows(db, framework)
                    )
            reason = (
                "Applicability is not configured for this official cycle. "
                "Official metrics are not treated as applicable until they "
                "are selected from this framework's operational catalogue."
                if official_operational_count
                else (
                    "This cycle's official metric catalogue is incomplete. "
                    "Seven verified criteria are not a complete or mandatory "
                    "metric set, so a final internal progress report cannot be "
                    "generated against it."
                )
            )
            return {
                **base,
                "institution_total_submissions": total_submissions,
                "institution_final_submitted_count": final_submitted_count,
                "eligible": False,
                "eligibility_status": "NOT_READY",
                "reason": reason,
            }
        eligible = final_submitted_count > 0
        return {
            **base,
            "institution_total_submissions": total_submissions,
            "institution_final_submitted_count": final_submitted_count,
            "eligible": eligible,
            "eligibility_status": "READY" if eligible else "NOT_READY",
            "reason": _legacy_eligibility_reason(
                eligible,
                final_submitted_count,
                final_approval_count,
                total_submissions,
            ),
        }

    if official_unverified:
        return {
            **base,
            "institution_total_submissions": total_submissions,
            "institution_final_submitted_count": final_submitted_count,
            "total_applicable_metrics": len(applicable),
            "eligible": False,
            "eligibility_status": "UNVERIFIED",
            "naac_required_optional_verified": False,
            "reason": (
                "Official NAAC required, optional, and not-applicable rules "
                "are not verified. required_default=false is not proof that "
                "a metric is optional. A final internal progress report "
                "cannot be treated as complete until those rules are "
                "confirmed."
            ),
        }

    submissions = query.all()
    cycle_submissions = [
        item for item in submissions if item.cycle_id == cycle.id
    ]
    base["institution_total_submissions"] = total_submissions
    base["institution_final_submitted_count"] = final_submitted_count
    base["total_submissions"] = len(cycle_submissions)
    base["final_submitted_count"] = len([
        item for item in cycle_submissions
        if item.status == "Final Submitted"
    ])
    base["final_approval_count"] = len([
        item for item in cycle_submissions
        if item.status == "Final Approval"
    ])
    if cycle:
        base["framework_id"] = getattr(cycle, "framework_id", None)
        framework = None
        if cycle.framework_id:
            framework = (
                db.query(NaacFramework)
                .filter(NaacFramework.id == cycle.framework_id)
                .first()
            )
        if framework:
            base["framework_name"] = framework.name
            base["framework_version"] = framework.version
            base["framework_code"] = framework.code
    documents = _scoped_document_query(db, institution_id).all()
    metric_ids = [item["metric_id"] for item in applicable]
    requirements = []
    if metric_ids:
        requirements = (
            db.query(EvidenceRequirement)
            .filter(EvidenceRequirement.metric_id.in_(metric_ids))
            .all()
        )
    requirements_by_metric: dict[int, list[EvidenceRequirement]] = {}
    for requirement in requirements:
        requirements_by_metric.setdefault(
            requirement.metric_id,
            [],
        ).append(requirement)

    missing_required_metrics = []
    missing_required_evidence = []
    finalized_metrics = []
    optional_pending_metrics = []
    finalized_required_count = 0
    pending_required_count = 0
    criterion_state: dict[int, dict] = {}

    for item in applicable:
        criterion_id = item["criterion_id"]
        if criterion_id not in criterion_state:
            criterion_state[criterion_id] = {
                "id": criterion_id,
                "number": item["criterion_number"],
                "title": item["criterion_title"],
                "applicable_metric_count": 0,
                "required_metric_count": 0,
                "finalized_required_count": 0,
            }
        state = criterion_state[criterion_id]
        state["applicable_metric_count"] += 1

        metric_submissions = _submissions_for_applicable_metric(
            cycle_submissions,
            item,
        )
        bucket = _classify_metric_bucket(metric_submissions)
        current_status = _current_submission_status(metric_submissions)
        ref = _metric_ref(item, bucket)
        if current_status:
            ref["current_status"] = current_status

        finalized_subs = [
            submission
            for submission in metric_submissions
            if submission.status == FINALIZED_SUBMISSION_STATUS
        ]
        needs_evidence = _metric_needs_evidence(
            item["metric"],
            requirements_by_metric.get(item["metric_id"], []),
        )
        has_evidence = _finalized_submissions_have_document(
            finalized_subs,
            documents,
        )
        evidence_ok = (not needs_evidence) or has_evidence
        institution_finalized = bucket == "finalized" and evidence_ok

        if item["required"]:
            state["required_metric_count"] += 1
            if institution_finalized:
                finalized_required_count += 1
                state["finalized_required_count"] += 1
                finalized_metrics.append(ref)
            else:
                pending_required_count += 1
                if not metric_submissions:
                    reason = "missing submission"
                elif bucket != "finalized":
                    reason = "not Final Submitted"
                else:
                    reason = "required evidence missing"
                missing_item = _eligibility_metric_item(
                    item,
                    reason,
                    current_status,
                )
                missing_required_metrics.append(missing_item)
                if reason == "required evidence missing":
                    missing_required_evidence.append(missing_item)
        else:
            if institution_finalized:
                finalized_metrics.append(ref)
            else:
                optional_pending_metrics.append(ref)

    criterion_readiness = []
    for state in sorted(
        criterion_state.values(),
        key=lambda item: item["id"],
    ):
        criterion_readiness.append({
            **state,
            "ready": (
                state["required_metric_count"]
                == state["finalized_required_count"]
            ),
        })

    eligible = pending_required_count == 0
    if eligible:
        reason = (
            "All required applicable metrics are Final Submitted. "
            "The institution final report is ready."
        )
    else:
        reason = (
            "The final report is not ready until every required applicable "
            "metric is Final Submitted"
        )
        if missing_required_evidence:
            reason += " with required evidence"
        reason += "."

    required_metric_count = finalized_required_count + pending_required_count
    return {
        **base,
        "eligible": eligible,
        "eligibility_status": "READY" if eligible else "NOT_READY",
        "reason": reason,
        "total_applicable_metrics": len(applicable),
        "required_metric_count": required_metric_count,
        "optional_metric_count": len(applicable) - required_metric_count,
        "finalized_required_count": finalized_required_count,
        "pending_required_count": pending_required_count,
        "missing_required_metrics": missing_required_metrics,
        "missing_required_evidence": missing_required_evidence,
        "finalized_metrics": finalized_metrics,
        "optional_pending_metrics": optional_pending_metrics,
        "criterion_readiness": criterion_readiness,
    }


