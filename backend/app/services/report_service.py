def _criterion_status(
    total_units: int,
    completed_units: int,
    started_units: int,
) -> str:
    if total_units == 0 or started_units == 0:
        return "Not Started"
    if completed_units >= total_units:
        return "Complete"
    return "In Progress"


FINALIZED_SUBMISSION_STATUS = "Final Submitted"


def get_active_cycle(
    db: Session,
    institution_id: int | None,
) -> AccreditationCycle | None:
    if institution_id is None:
        return None

    query = db.query(AccreditationCycle).filter(
        AccreditationCycle.institution_id == institution_id
    )

    active = (
        query.filter(AccreditationCycle.status.in_(ACTIVE_CYCLE_STATUSES))
        .order_by(AccreditationCycle.id.desc())
        .first()
    )
    if active:
        return active

    return (
        query.filter(AccreditationCycle.status != "Completed")
        .order_by(AccreditationCycle.id.desc())
        .first()
    )


def get_live_cycle(
    db: Session,
    institution_id: int | None,
) -> AccreditationCycle | None:
    """Newest Active / In Progress cycle. Draft and Archived never qualify."""
    if institution_id is None:
        return None
    return (
        db.query(AccreditationCycle)
        .filter(
            AccreditationCycle.institution_id == institution_id,
            AccreditationCycle.status.in_(ACTIVE_CYCLE_STATUSES),
        )
        .order_by(AccreditationCycle.id.desc())
        .first()
    )


def get_latest_completed_cycle(
    db: Session,
    institution_id: int | None,
) -> AccreditationCycle | None:
    if institution_id is None:
        return None

    return (
        db.query(AccreditationCycle)
        .filter(
            AccreditationCycle.status == "Completed",
            AccreditationCycle.institution_id == institution_id,
        )
        .order_by(AccreditationCycle.id.desc())
        .first()
    )


def cycle_has_unverified_official_requirement_rules(
    db: Session,
    cycle: AccreditationCycle | None,
) -> bool:
    """Official RAF cycles do not have verified required/optional/NA rules.

    required_default=false is a source placeholder, not proof a metric is
    optional. INTERNAL and unbound working cycles keep working-catalogue rules.
    """
    if cycle is None or not getattr(cycle, "framework_id", None):
        return False
    framework = (
        db.query(NaacFramework)
        .filter(NaacFramework.id == cycle.framework_id)
        .first()
    )
    if not framework or framework.code == CODE_INTERNAL:
        return False
    return True


def final_report_relative_path(institution_id: int, cycle_id: int) -> str:
    return (
        f"/uploads/reports/institution_{institution_id}/"
        f"cycle_{cycle_id}/{FINAL_REPORT_FILENAME}"
    )


def final_report_absolute_path(institution_id: int, cycle_id: int) -> Path:
    path = (
        REPORTS_ROOT
        / f"institution_{institution_id}"
        / f"cycle_{cycle_id}"
        / FINAL_REPORT_FILENAME
    ).resolve()
    if not path.is_relative_to(REPORTS_ROOT.resolve()):
        raise ValueError("Invalid final report path")
    return path


def stored_final_report_exists(institution_id: int, cycle_id: int) -> bool:
    try:
        path = final_report_absolute_path(institution_id, cycle_id)
    except ValueError:
        return False
    return path.is_file()


def persist_final_report_html(
    institution_id: int,
    cycle_id: int,
    html: str,
) -> str:
    destination = final_report_absolute_path(institution_id, cycle_id)
    destination.parent.mkdir(parents=True, exist_ok=True)

    # Windows: O_CREAT|O_EXCL on an existing *directory* raises
    # PermissionError (Errno 13 / ACCESS_DENIED), not FileExistsError.
    # An empty leftover directory is not a stored report; a real HTML
    # file must never be overwritten.
    if destination.is_file():
        raise FileExistsError(str(destination))
    if destination.is_dir():
        try:
            destination.rmdir()
        except OSError as exc:
            raise FileExistsError(str(destination)) from exc

    encoded = html.encode("utf-8")
    flags = os.O_CREAT | os.O_EXCL | os.O_WRONLY
    if hasattr(os, "O_BINARY"):
        flags |= os.O_BINARY
    try:
        handle = os.open(str(destination), flags, 0o666)
    except FileExistsError:
        raise
    except PermissionError as exc:
        if destination.exists():
            raise FileExistsError(str(destination)) from exc
        raise
    try:
        with os.fdopen(handle, "wb") as file_obj:
            file_obj.write(encoded)
    except Exception:
        try:
            destination.unlink(missing_ok=True)
        except OSError:
            pass
        raise
    return final_report_relative_path(institution_id, cycle_id)


def remove_final_report_file(institution_id: int, cycle_id: int) -> None:
    try:
        path = final_report_absolute_path(institution_id, cycle_id)
    except ValueError:
        return
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass


def read_stored_final_report(
    institution_id: int,
    cycle_id: int,
) -> bytes | None:
    if not stored_final_report_exists(institution_id, cycle_id):
        return None
    path = final_report_absolute_path(institution_id, cycle_id)
    return path.read_bytes()


def _percent(completed: int, total: int, digits: int = 1) -> float:
    if total <= 0:
        return 0.0
    return round((completed / total * 100), digits)


def _submissions_for_applicable_metric(
    submissions: list[Submission],
    item: dict,
) -> list[Submission]:
    catalog_kind = item.get("catalog_kind")
    metric = item.get("metric")
    if catalog_kind is None and metric is not None:
        catalog_kind = getattr(metric, "catalog_kind", None)
    if catalog_kind == CATALOG_KIND_OFFICIAL:
        metric_id = item.get("metric_id")
        return [
            submission
            for submission in submissions
            if submission.metric_id is not None
            and submission.metric_id == metric_id
        ]
    return [
        submission
        for submission in submissions
        if submission.metric_code == item.get("metric_code")
    ]


def _classify_metric_bucket(submissions: list[Submission]) -> str:
    statuses = {item.status for item in submissions}
    if FINALIZED_SUBMISSION_STATUS in statuses:
        return "finalized"
    if "Under Review" in statuses:
        return "under_review"
    if "Changes Requested" in statuses:
        return "changes_requested"
    if "Rejected" in statuses:
        return "rejected"
    return "pending"


def _metric_ref(item: dict, bucket: str | None = None) -> dict:
    payload = {
        "metric_id": item["metric_id"],
        "metric_code": item["metric_code"],
        "metric_title": item["metric_title"],
        "required": item["required"],
        "criterion_id": item["criterion_id"],
        "criterion_number": item["criterion_number"],
        "criterion_title": item["criterion_title"],
    }
    if bucket is not None:
        payload["status_bucket"] = bucket
    return payload


