def _attach_framework_metadata(
    db: Session,
    cycle: AccreditationCycle | None,
    cycle_progress: dict,
) -> dict:
    if not cycle or not getattr(cycle, "framework_id", None):
        return cycle_progress
    framework = (
        db.query(NaacFramework)
        .filter(NaacFramework.id == cycle.framework_id)
        .first()
    )
    if not framework:
        return cycle_progress
    cycle_progress["framework_id"] = framework.id
    cycle_progress["framework_name"] = framework.name
    cycle_progress["framework_version"] = framework.version
    cycle_progress["framework_code"] = framework.code
    cycle_progress["framework_verification_status"] = (
        framework.verification_status
    )
    from app.services.framework_service import framework_readiness
    readiness = framework_readiness(db, framework)
    cycle_progress["criterion_structure_verified"] = readiness[
        "criterion_structure_verified"
    ]
    cycle_progress["metric_catalogue_complete"] = readiness[
        "metric_catalogue_complete"
    ]
    cycle_progress["catalogue_status"] = readiness["catalogue_status"]
    return cycle_progress


def _funnel_from_submissions(submissions: list[Submission]) -> dict:
    def count_status(name: str) -> int:
        return len([item for item in submissions if item.status == name])

    return {
        "total": len(submissions),
        "draft": count_status("Draft"),
        "submitted": count_status("Submitted"),
        "under_review": count_status("Under Review"),
        "resubmitted": count_status("Resubmitted"),
        "approved": count_status("Approved"),
        "rejected": count_status("Rejected"),
        "changes_requested": count_status("Changes Requested"),
        "final_approval": count_status("Final Approval"),
        "final_submitted": count_status("Final Submitted"),
    }


def resolve_progress_cycle(
    db: Session,
    institution_id: int | None,
) -> tuple[AccreditationCycle | None, bool, list[dict]]:
    cycle = get_active_cycle(db, institution_id)
    if not cycle:
        return None, False, []
    catalog = load_applicable_metric_catalog(db, cycle.id)
    return cycle, len(catalog) > 0, catalog


def _scoped_submissions(
    db: Session,
    institution_id: int | None = None,
    department_id: int | None = None,
):
    query = db.query(Submission)
    if institution_id:
        query = query.filter(Submission.institution_id == institution_id)
    if department_id:
        query = query.filter(Submission.department_id == department_id)
    return query


def _progress_flags(
    cycle: AccreditationCycle | None,
    configured: bool,
) -> dict:
    return {
        "progress_cycle_id": cycle.id if cycle else None,
        "applicability_configured": configured,
        "uses_catalog_fallback": not configured,
    }


def _compute_catalog_fallback_progress(
    db: Session,
    institution_id: int | None,
    department_id: int | None,
    cycle: AccreditationCycle | None,
    submissions: list[Submission],
    documents: list[Document],
) -> dict:
    criteria_query = db.query(Criterion)
    if cycle:
        criteria_query = criteria_query.filter(
            (Criterion.cycle_id == cycle.id) | (Criterion.cycle_id.is_(None))
        )
    criteria = criteria_query.order_by(Criterion.id).all()
    sections = db.query(Section).all()
    metrics = (
        db.query(Metric)
        .filter(Metric.catalog_kind == CATALOG_KIND_WORKING)
        .all()
    )
    sections_by_criterion: dict[int, list[Section]] = {}
    for section in sections:
        sections_by_criterion.setdefault(section.criterion_id, []).append(section)

    metrics_by_section: dict[int, list[Metric]] = {}
    for metric in metrics:
        metrics_by_section.setdefault(metric.section_id, []).append(metric)

    flags = _progress_flags(cycle, configured=False)
    results = []
    for criterion in criteria:
        criterion_sections = sections_by_criterion.get(criterion.id, [])
        criterion_metrics = []
        for section in criterion_sections:
            criterion_metrics.extend(metrics_by_section.get(section.id, []))

        criterion_submissions = [
            item for item in submissions if item.criterion_id == criterion.id
        ]
        submission_ids = {item.id for item in criterion_submissions}
        evidence_count = len([
            document
            for document in documents
            if document.submission_id in submission_ids
        ])
        approved_submissions = [
            item
            for item in criterion_submissions
            if item.status in APPROVED_SUBMISSION_STATUSES
        ]

        if criterion_metrics:
            completed_metrics = 0
            started_metrics = 0
            finalized_count = 0
            pending_count = 0
            under_review_count = 0
            changes_requested_count = 0
            rejected_count = 0
            for metric in criterion_metrics:
                metric_submissions = [
                    item
                    for item in criterion_submissions
                    if item.metric_code == metric.code
                ]
                bucket = _classify_metric_bucket(metric_submissions)
                if bucket == "finalized":
                    finalized_count += 1
                elif bucket == "under_review":
                    under_review_count += 1
                elif bucket == "changes_requested":
                    changes_requested_count += 1
                elif bucket == "rejected":
                    rejected_count += 1
                else:
                    pending_count += 1
                if metric_submissions:
                    started_metrics += 1
                    if any(
                        item.status in APPROVED_SUBMISSION_STATUSES
                        for item in metric_submissions
                    ):
                        completed_metrics += 1

            total_units = len(criterion_metrics)
            completed_units = completed_metrics
            started_units = started_metrics
        else:
            total_units = len(criterion_submissions)
            completed_units = len(approved_submissions)
            started_units = len(criterion_submissions)
            finalized_count = len([
                item for item in criterion_submissions
                if item.status == FINALIZED_SUBMISSION_STATUS
            ])
            pending_count = 0
            under_review_count = 0
            changes_requested_count = 0
            rejected_count = 0

        results.append({
            "id": criterion.id,
            "number": criterion.number,
            "title": criterion.title,
            "weightage": criterion.weightage,
            "description": criterion.description,
            "cycle_id": criterion.cycle_id,
            "status": _criterion_status(
                total_units,
                completed_units,
                started_units,
            ),
            "total_submissions": len(criterion_submissions),
            "approved_submissions": len(approved_submissions),
            "total_metrics": len(criterion_metrics),
            "total_evidence": evidence_count,
            "completion_percentage": _percent(completed_units, total_units, 1),
            "created_at": criterion.created_at,
            "updated_at": criterion.updated_at,
            "required_metric_count": len(criterion_metrics),
            "optional_metric_count": 0,
            "finalized_count": finalized_count,
            "pending_count": pending_count,
            "under_review_count": under_review_count,
            "changes_requested_count": changes_requested_count,
            "rejected_count": rejected_count,
            "missing_required_count": 0,
            **flags,
        })

    total_comp_sum = sum(item["completion_percentage"] for item in results)
    overall = (
        round((total_comp_sum / len(results)), 1)
        if results
        else 0.0
    )
    catalog_metric_count = sum(item["total_metrics"] or 0 for item in results)
    cycle_progress = _empty_cycle_progress(
        cycle,
        configured=False,
        fallback=True,
    )
    cycle_progress["total_applicable_metrics"] = catalog_metric_count
    cycle_progress["completion_percentage"] = overall
    return {
        "criteria": results,
        "cycle_progress": cycle_progress,
    }


def _compute_configured_cycle_progress(
    cycle: AccreditationCycle,
    applicable: list[dict],
    submissions: list[Submission],
    documents: list[Document],
) -> dict:
    cycle_submissions = [
        item for item in submissions if item.cycle_id == cycle.id
    ]
    flags = _progress_flags(cycle, configured=True)

    classified = []
    for item in applicable:
        metric_submissions = _submissions_for_applicable_metric(
            cycle_submissions,
            item,
        )
        bucket = _classify_metric_bucket(metric_submissions)
        classified.append({
            **item,
            "bucket": bucket,
            "submissions": metric_submissions,
        })

    by_criterion: dict[int, list[dict]] = {}
    for item in classified:
        by_criterion.setdefault(item["criterion_id"], []).append(item)

    results = []
    for criterion_items in by_criterion.values():
        criterion = criterion_items[0]["criterion"]
        all_submissions = []
        for item in criterion_items:
            all_submissions.extend(item["submissions"])
        submission_ids = {item.id for item in all_submissions}
        evidence_count = len([
            document
            for document in documents
            if document.submission_id in submission_ids
        ])
        approved_submissions = [
            item
            for item in all_submissions
            if item.status in APPROVED_SUBMISSION_STATUSES
        ]

        finalized_count = len([
            item for item in criterion_items if item["bucket"] == "finalized"
        ])
        pending_count = len([
            item for item in criterion_items if item["bucket"] == "pending"
        ])
        under_review_count = len([
            item for item in criterion_items if item["bucket"] == "under_review"
        ])
        changes_requested_count = len([
            item for item in criterion_items
            if item["bucket"] == "changes_requested"
        ])
        rejected_count = len([
            item for item in criterion_items if item["bucket"] == "rejected"
        ])
        required_count = len([
            item for item in criterion_items if item["required"]
        ])
        optional_count = len(criterion_items) - required_count
        missing_required_count = len([
            item for item in criterion_items
            if item["required"] and item["bucket"] != "finalized"
        ])
        started_units = len([
            item for item in criterion_items if item["submissions"]
        ])
        total_units = len(criterion_items)

        results.append({
            "id": criterion.id,
            "number": criterion.number,
            "title": criterion.title,
            "weightage": criterion.weightage,
            "description": criterion.description,
            "cycle_id": criterion.cycle_id,
            "status": _criterion_status(
                total_units,
                finalized_count,
                started_units,
            ),
            "total_submissions": len(all_submissions),
            "approved_submissions": len(approved_submissions),
            "total_metrics": total_units,
            "total_evidence": evidence_count,
            "completion_percentage": _percent(finalized_count, total_units, 2),
            "created_at": criterion.created_at,
            "updated_at": criterion.updated_at,
            "required_metric_count": required_count,
            "optional_metric_count": optional_count,
            "finalized_count": finalized_count,
            "pending_count": pending_count,
            "under_review_count": under_review_count,
            "changes_requested_count": changes_requested_count,
            "rejected_count": rejected_count,
            "missing_required_count": missing_required_count,
            **flags,
        })

    results.sort(key=lambda item: item["id"])

    bucket_lists = {
        "finalized": [],
        "pending": [],
        "under_review": [],
        "changes_requested": [],
        "rejected": [],
    }
    required_metrics = []
    optional_metrics = []
    missing_required_metrics = []
    finalized_required_count = 0
    pending_required_count = 0

    for item in classified:
        ref = _metric_ref(item, item["bucket"])
        bucket_lists[item["bucket"]].append(ref)
        if item["required"]:
            required_metrics.append(ref)
            if item["bucket"] == "finalized":
                finalized_required_count += 1
            else:
                pending_required_count += 1
                missing_required_metrics.append(ref)
        else:
            optional_metrics.append(ref)

    total_applicable = len(classified)
    finalized_count = len(bucket_lists["finalized"])
    cycle_progress = {
        "cycle_id": cycle.id,
        "cycle_name": cycle.name,
        "applicability_configured": True,
        "uses_catalog_fallback": False,
        "total_applicable_metrics": total_applicable,
        "required_metric_count": len(required_metrics),
        "optional_metric_count": len(optional_metrics),
        "finalized_count": finalized_count,
        "finalized_required_count": finalized_required_count,
        "pending_required_count": pending_required_count,
        "pending_count": len(bucket_lists["pending"]),
        "under_review_count": len(bucket_lists["under_review"]),
        "changes_requested_count": len(bucket_lists["changes_requested"]),
        "rejected_count": len(bucket_lists["rejected"]),
        "completion_percentage": _percent(finalized_count, total_applicable, 2),
        "required_metrics_complete": pending_required_count == 0,
        "missing_required_metrics": missing_required_metrics,
        "required_metrics": required_metrics,
        "optional_metrics": optional_metrics,
        "finalized_metrics": bucket_lists["finalized"],
        "pending_metrics": bucket_lists["pending"],
        "under_review_metrics": bucket_lists["under_review"],
        "changes_requested_metrics": bucket_lists["changes_requested"],
        "rejected_metrics": bucket_lists["rejected"],
    }
    return {
        "criteria": results,
        "cycle_progress": cycle_progress,
    }


def build_progress(
    db: Session,
    institution_id: int | None = None,
    department_id: int | None = None,
    cycle: AccreditationCycle | None = None,
) -> dict:
    if cycle is None:
        cycle, configured, applicable = resolve_progress_cycle(
            db,
            institution_id,
        )
    else:
        applicable = load_applicable_metric_catalog(db, cycle.id)
        configured = bool(applicable)

    submissions_query = _scoped_submissions(
        db,
        institution_id,
        department_id,
    )
    if cycle:
        submissions_query = submissions_query.filter(
            Submission.cycle_id == cycle.id
        )
    submissions = submissions_query.all()
    documents = _scoped_document_query(db, institution_id).all()
    if department_id:
        submission_ids = {item.id for item in submissions}
        documents = [
            document
            for document in documents
            if document.submission_id in submission_ids
        ]

    if configured:
        result = _compute_configured_cycle_progress(
            cycle,
            applicable,
            submissions,
            documents,
        )
    elif cycle and uses_working_catalog_fallback(db, cycle):
        result = _compute_catalog_fallback_progress(
            db,
            institution_id,
            department_id,
            cycle,
            submissions,
            documents,
        )
    else:
        result = {
            "criteria": [],
            "cycle_progress": _empty_cycle_progress(
                cycle,
                configured=False,
                fallback=False,
            ),
        }
    result["cycle_progress"] = _attach_framework_metadata(
        db,
        cycle,
        result["cycle_progress"],
    )
    if cycle_has_unverified_official_requirement_rules(db, cycle):
        configured = bool(
            result["cycle_progress"].get("applicability_configured")
        )
        status = "UNVERIFIED" if configured else "NOT_READY"
        result["cycle_progress"]["naac_required_optional_verified"] = False
        result["cycle_progress"]["eligibility_status"] = status
        result["cycle_progress"]["required_metric_count"] = 0
        result["cycle_progress"]["optional_metric_count"] = 0
        result["cycle_progress"]["optional_metrics"] = []
        result["cycle_progress"]["required_metrics"] = []
        result["cycle_progress"]["required_metrics_complete"] = False
        result["cycle_progress"]["missing_required_metrics"] = []
        for item in result["criteria"]:
            item["optional_metric_count"] = 0
            item["required_metric_count"] = 0
            item["missing_required_count"] = 0
            item["eligibility_status"] = status
            item["naac_required_optional_verified"] = False
    return result


